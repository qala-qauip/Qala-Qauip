export type IconName = keyof typeof ICON_MAP;

export function lucideSvg(name: IconName, className = 'w-4 h-4'): string {
  const node = ICON_MAP[name];
  const el = createElement(node, {
    class: className,
    'stroke-width': 1.9,
  });
  return el.outerHTML;
}

